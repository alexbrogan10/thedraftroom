# draft_projections.csv — 2-3 scouting sources per prospect, picks driven by
# talent + independent per-source noise (so sources disagree realistically)
# ---------------------------------------------------------------------------
SOURCES = ["Consensus Big Board", "Scouting Network A", "Draft Analytics Co."]
proj_rows = []
n_prospects = len(prospects)
# Rank-based (not raw-value-based) mapping from latent talent to a base pick,
# so picks spread across the full ~1-262 draft-pick range regardless of the
# shape of the talent distribution — avoids clustering everyone into the
# late picks, which would otherwise distort the Hidden Value Finder's
# analytical-rank-vs-expected-pick comparison.
talent_order = sorted(prospects, key=lambda pr: talent[pr["id"]], reverse=True)
base_pick_by_id = {
    pr["id"]: 1 + i * (261 / max(1, n_prospects - 1)) for i, pr in enumerate(talent_order)
}
for p in prospects:
    base_pick = base_pick_by_id[p["id"]]
    n_sources = random.choice([2, 2, 3])
    for source in random.sample(SOURCES, n_sources):
        pick = clamp(round(base_pick + np.random.normal(0, 14)), 1, 262)
        proj_rows.append({
            "prospect_id": p["id"], "source": source,
            "projected_pick": int(pick), "projected_round": int((pick - 1) // 32 + 1),
        })
pd.DataFrame(proj_rows).to_csv(DATA_RAW / "draft_projections.csv", index=False)

