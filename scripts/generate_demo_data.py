# historical_drafts.csv — FICTIONAL demo comparison players (see disclosure)
# ---------------------------------------------------------------------------
hist_rows = []
outcome_rows = []
hid = 1
for position in POSITION_COUNTS:
    for _ in range(25):
        t = np.random.beta(2, 2)
        lo_h, hi_h = HEIGHT_RANGE[position]
        lo_w, hi_w = WEIGHT_RANGE[position]
        forty_lo, forty_hi = COMBINE_RANGES[position]["forty_yard_dash"]
        draft_year_hist = random.randint(2013, 2021)  # old enough for a full outcome window
        draft_pick = int(clamp(1 + (1 - t) * 250, 1, 262))
        hist_rows.append({
            "id": hid,
            "player_name": unique_name(),
            "position": position,
            "college": random.choice(COLLEGES),
            "draft_year": draft_year_hist,
            "draft_round": int(clamp(1 + (1 - t) * 6, 1, 7)),
            "draft_pick": draft_pick,
            "age": round(clamp(np.random.normal(21.3, 1.0), 20, 24), 1),
            "height_inches": round(np.random.uniform(lo_h, hi_h), 1),
            "weight_lbs": round(np.random.uniform(lo_w, hi_w), 0),
            "forty_yard_dash": round(forty_hi - (forty_hi - forty_lo) * t, 2),
            "college_production_score": round(clamp(t * 100 + np.random.normal(0, 6), 0, 100), 1),
        })

        # NFL OUTCOME LABELS (demo-only, synthetic — see docs/model_documentation.md
        # for the real label definitions this schema is designed to support).
        # Deliberately imperfectly correlated with pre-draft talent `t`, to
        # simulate that draft outcomes are genuinely uncertain.
        outcome_luck = np.random.normal(0, 0.30)
        outcome_strength = clamp(t + outcome_luck, 0, 1)
        started = outcome_strength > 0.45
        productive_starter = started and outcome_strength > 0.68
        long_term_contributor = started and outcome_strength > 0.55 and random.random() > 0.2
        seasons_played = int(clamp(round(2 + outcome_strength * 8 + np.random.normal(0, 1)), 1, 12))
        starts = int(clamp(round(outcome_strength * seasons_played * 15), 0, seasons_played * 16))
        games = int(clamp(starts + np.random.randint(0, 8), starts, seasons_played * 17))

        outcome_rows.append({
            "historical_id": hid,
            "season": draft_year_hist + 3,
            "games": games,
            "starts": starts,
            "started": bool(started),
            "productive_starter": bool(productive_starter),
            "long_term_contributor": bool(long_term_contributor),
        })
        hid += 1
