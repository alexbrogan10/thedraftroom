# ---------------------------------------------------------------------------
# team_needs.csv — derived from roster depth at each position, projected
# across three seasons with a mild aging-driven trend.
# ---------------------------------------------------------------------------
needs_rows = []
roster_df = pd.DataFrame(roster_rows)
players_df = pd.DataFrame(player_rows)
merged = roster_df.merge(players_df, left_on="player_id", right_on="id", suffixes=("", "_p"))

for team in teams_df.itertuples():
    team_roster = merged[merged.team_id == team.id]
    for position in ROSTER_POSITIONS:
        pos_players = team_roster[team_roster.position == position]
        count = len(pos_players)
        avg_age = pos_players.age.mean() if count else 27.0
        base_need = clamp(90 - count * 22, 10, 95)
        for season_offset, season in enumerate([CURRENT_SEASON, CURRENT_SEASON + 1, CURRENT_SEASON + 2]):
            aging_pressure = max(0, avg_age - 28) * 3 * (season_offset + 1)
            need_score = round(clamp(base_need + aging_pressure + np.random.normal(0, 4), 5, 98), 1)
            needs_rows.append({
                "team_id": team.id, "position": position, "season": season, "need_score": need_score,
            })
pd.DataFrame(needs_rows).to_csv(DATA_RAW / "team_needs.csv", index=False)

