import { useEffect, useState } from "react";
import { ModelAPI } from "../services/api";
import type { ModelPerformance } from "../types";
import { Card, Loading } from "../components/Card";

const LABEL_TITLES: Record<string, string> = {
  started: "NFL Starter Classification",
  productive_starter: "Productive Starter Classification",
  long_term_contributor: "Long-Term Contributor Classification",
};

export function Methodology() {
  const [perf, setPerf] = useState<ModelPerformance | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    ModelAPI.performance()
      .then(setPerf)
      .finally(() => setLoading(false));
  }, []);

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-xl font-semibold text-[var(--color-text)]">Data &amp; Model Performance</h1>
        <p className="mt-1 max-w-3xl text-sm text-[var(--color-text-muted)]">
          The Draft Room is an independent football analytics and portfolio project. It is not affiliated with,
          endorsed by, or associated with the National Football League, NFL teams, or the NFL Draft. All prospect
          evaluations, rankings, projections, and recommendations are analytical estimates generated from available
          data and should not be interpreted as professional scouting advice.
        </p>
      </div>

      <Card title="Demo Data Disclosure">
        <p className="text-sm text-[var(--color-text-muted)]">
          Team names, abbreviations, conferences, and divisions are real public NFL organizational facts. Every
          prospect, roster player, historical comparison player, statistic, combine result, projection, and team
          need in this deployment is <strong>synthetic demo data</strong>, generated by a seeded script
          (<code className="rounded bg-[var(--color-panel-raised)] px-1">scripts/generate_demo_data.py</code>) to
          exercise the analytics pipeline end-to-end. No real player statistics or proprietary NFL data are used or
          represented. See <code className="rounded bg-[var(--color-panel-raised)] px-1">docs/data_sources.md</code>.
        </p>
      </Card>

      <Card title="Draft Grade Methodology">
        <p className="text-sm text-[var(--color-text-muted)]">
          Draft Grade blends six explainable components. Default weights (configurable via environment variables,
          see <code className="rounded bg-[var(--color-panel-raised)] px-1">.env.example</code>):
        </p>
        <div className="mt-3 grid grid-cols-2 gap-2 sm:grid-cols-3">
          {[
            ["Production", "25%"],
            ["Athletic Profile", "15%"],
            ["Age / Experience", "10%"],
            ["Position Value", "15%"],
            ["NFL Projection", "25%"],
            ["Risk Adjustment", "10%"],
          ].map(([label, weight]) => (
            <div key={label} className="rounded border border-[var(--color-border)] bg-[var(--color-panel-raised)] p-2.5 text-center">
              <div className="text-xs text-[var(--color-text-faint)]">{label}</div>
              <div className="font-mono text-lg text-[var(--color-accent)]">{weight}</div>
            </div>
          ))}
        </div>
        <p className="mt-3 text-xs text-[var(--color-text-faint)]">
          Production and Athletic Profile are percentile ranks within a prospect's position group in its draft
          class. NFL Projection is currently a transparent heuristic blend of production, testing, and scouting
          consensus — see full methodology in docs/scoring_methodology.md.
        </p>
      </Card>

      <Card title="NFL Outcome Prediction — Model Performance" subtitle="scikit-learn RandomForestClassifier, trained on pre-draft-only features">
        {loading && <Loading label="Loading model metrics..." />}
        {!loading && perf && !perf.available && (
          <p className="text-sm text-[var(--color-text-faint)]">{perf.message}</p>
        )}
        {!loading && perf?.available && perf.labels && (
          <div className="space-y-4">
            <p className="text-xs text-[var(--color-text-faint)]">{perf.disclaimer}</p>
            <div className="grid grid-cols-1 gap-4 lg:grid-cols-3">
              {Object.entries(perf.labels).map(([key, m]) => (
                <div key={key} className="rounded border border-[var(--color-border)] bg-[var(--color-panel-raised)] p-3">
                  <div className="text-sm font-medium text-[var(--color-text)]">{LABEL_TITLES[key] ?? key}</div>
                  <dl className="mt-2 space-y-1 text-xs">
                    <MetricRow label="Accuracy" value={m.accuracy} />
                    <MetricRow label="Precision" value={m.precision} />
                    <MetricRow label="Recall" value={m.recall} />
                    <MetricRow label="F1" value={m.f1} />
                    <MetricRow label="ROC-AUC" value={m.roc_auc} />
                  </dl>
                  <div className="mt-2 text-[10px] text-[var(--color-text-faint)]">
                    Trained on {m.n_train} samples, evaluated on {m.n_test} held out.
                  </div>
                </div>
              ))}
            </div>
            <p className="text-xs text-[var(--color-text-faint)]">
              Historical performance does not guarantee future predictive accuracy. Trained {perf.trained_at ? new Date(perf.trained_at).toLocaleString() : "—"} on {perf.n_samples} historical demo records.
            </p>
          </div>
        )}
      </Card>

      <Card title="Data Leakage Prevention">
        <p className="text-sm text-[var(--color-text-muted)]">
          Outcome prediction features are strictly limited to information knowable before a player is drafted (age,
          height, weight, 40-yard dash, college production percentile, draft pick/round). NFL rookie/career
          statistics, Pro Bowls, and contracts are used only to construct training LABELS in{" "}
          <code className="rounded bg-[var(--color-panel-raised)] px-1">nfl_outcomes</code>, never as model inputs.
          See docs/model_documentation.md for the full rule set.
        </p>
      </Card>
    </div>
  );
}

function MetricRow({ label, value }: { label: string; value: number | null }) {
  return (
    <div className="flex justify-between">
      <dt className="text-[var(--color-text-faint)]">{label}</dt>
      <dd className="font-mono text-[var(--color-text)]">{value != null ? `${(value * 100).toFixed(1)}%` : "—"}</dd>
    </div>
  );
}
